#!/usr/bin/env python3
"""
Design Portfolio Automation Generator
Creates professional design portfolios for frontend/designer projects.
Integrates with Hermes Agent workflows.
Usage: python scripts/portfolio/generate.py --project "Name" --client "Client"
"""

import argparse
import sys
import os
from pathlib import Path


def generate_portfolio(project, client="", theme="modern", output_dir="."):
    """Generate a complete design portfolio."""
    
    # Ensure output directory
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    
    # Generate files
    generate_index(out, project, client, theme)
    generate_branding(out)
    generate_typography(out)
    generate_wireframes(out)
    generate_motion(out)
    generate_3d(out, theme)
    generate_web_layouts(out)
    generate_story(out, project)
    
    print(f"✓ Portfolio generated: {out / 'index.html'}")
    print(f"  Project: {project}")
    print(f"  Client: {client or 'Not specified'}")
    print(f"  Sections: Brand, Typography, Wireframes, Motion, 3D, Web, Story")


def generate_index(out, project, client, theme):
    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"><title>{project} - Design Portfolio</title>
<link rel="stylesheet" href="assets/color-palette.css">
<link rel="stylesheet" href="assets/typography.css">
<style>
  body {{ font-family: 'Inter', sans-serif; max-width: 1200px; margin: 0 auto; padding: 2rem; color: #0f172a; background: #f8fafc; }}
  .hero {{ background: #0f172a; color: white; padding: 6rem 2rem; border-radius: 1rem; margin-bottom: 4rem; text-align: center; }}
  .hero h1 {{ font-size: 3rem; letter-spacing: -0.02em; margin-bottom: 1rem; }}
  .hero p {{ font-size: 1.125rem; color: #94a3b8; }}
  .sections {{ display: grid; gap: 2rem; }}
  .section-card {{ background: white; border: 1px solid #e2e8f0; border-radius: 1rem; padding: 2rem; }}
  .section-card h2 {{ font-size: 1.5rem; margin-bottom: 1rem; }}
  .tag {{ display: inline-block; padding: 0.25rem 1rem; background: #f0f9ff; color: #0694a3; border-radius: 9999px; font-size: 0.875rem; font-weight: 500; margin: 0.25rem; }}
</style>
</head>
<body>
  <div class="hero">
    <h1>{project}</h1>
    <p>Design Portfolio • {client or 'Private Portfolio'} • {theme.title()} Theme</p>
  </div>

  <div class="sections">
    <section class="section-card"><h2>Branding</h2><p>Logo, palette, typography, voice. See sections/02-branding.md</p></section>
    <section class="section-card"><h2>Typography System</h2><p>Scale, hierarchy, font pairing. See sections/01-typography.md</p></section>
    <section class="section-card"><h2>UI/UX Wireframes</h2><p>Mockups, wireframes, accessibility. See sections/03-ux-wireframes.md</p></section>
    <section class="section-card"><h2>Motion Design</h2><p>Animation concepts, timing, GSAP. See sections/04-motion-design.md</p></section>
    <section class="section-card"><h2>3D Visualization</h2><p>WebGL, Three.js, model showcases. See sections/05-3d-visualization.md</p></section>
    <section class="section-card"><h2>Web Layouts</h2><p>Responsive pages, landing pages, components. See sections/06-web-layouts.md</p></section>
    <section class="section-card"><h2>Story</h2><p>Case study framework, copywriting. See sections/07-story-narrative.md</p></section>
  </div>

  <footer style="margin-top: 4rem; padding-top: 2rem; border-top: 1px solid #e2e8f0; color: #64748b; font-size: 0.875rem;">
    Generated by Design Portfolio Automation • Hermes Agent Workflow • {theme.title()}
  </footer>
</body>
</html>"""
    (out / "index.html").write_text(html)


def generate_branding(out):
    (out / "branding.md").write_text(open("portfolio-automation/sections/02-branding.md").read())


def generate_typography(out):
    (out / "typography.md").write_text(open("portfolio-automation/sections/01-typography.md").read())


def generate_wireframes(out):
    (out / "wireframes.md").write_text(open("portfolio-automation/sections/03-ux-wireframes.md").read())


def generate_motion(out):
    (out / "motion.md").write_text(open("portfolio-automation/sections/04-motion-design.md").read())


def generate_3d(out, theme):
    (out / "3d.md").write_text(open("portfolio-automation/sections/05-3d-visualization.md").read())


def generate_web_layouts(out):
    (out / "web-layouts.md").write_text(open("portfolio-automation/sections/06-web-layouts.md").read())


def generate_story(out, project):
    (out / "story.md").write_text(open("portfolio-automation/sections/07-story-narrative.md").read().replace("[Project Name]", project))


def main():
    parser = argparse.ArgumentParser(description="Design Portfolio Automation Generator")
    parser.add_argument("--project", default="Portfolio Project", help="Project name")
    parser.add_argument("--client", default="", help="Client/Brand")
    parser.add_argument("--theme", default="modern", choices=["modern", "minimal", "creative", "bold"], help="Design theme")
    parser.add_argument("--output", default="portfolio-output", help="Output directory")
    args = parser.parse_args()
    generate_portfolio(args.project, args.client, args.theme, args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
